#include "3-calc.h"

/**
 * op_add - Addition Function
 * @a: First integer
 * @b: Second integer
 * Return: returns result
 */

int op_add(int a, int b)
{
	int result;

	result = a + b;

	return (result);
}

/**
 * op_sub - Subtraction function
 * @a: first integer
 * @b: second integer
 * Return: returns result
 */

int op_sub(int a, int b)
{
	int result;

	result = a - b;

	return (result);
}

/**
 * op_mul - Multiply function
 * @a: first integer
 * @b: second integer
 * Return: returns result
 */

int op_mul(int a, int b)
{
	int result;

	result = a * b;

	return (result);
}

/**
 * op_div - Division function
 * @a: first integer
 * @b: second integer
 * Return: returns result
 */

int op_div(int a, int b)
{
	int result;

	result = a / b;

	return (result);
}

/**
 * op_mod - Modulos function
 * @a: first integer
 * @b: second integer
 * Return: returns result
 */

int op_mod(int a, int b)
{
	int result;

	result = a % b;

	return (result);
}
